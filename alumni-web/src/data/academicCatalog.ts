export function findUniversity(value?: string | null) {
  const normalized = normalizeAcademicText(value);
  if (!normalized) return null;

  const aliasId = ALIASES[normalized];
  if (aliasId) {
    return ACADEMIC_UNIVERSITIES.find((item) => item.id === aliasId) ?? null;
  }

  return (
    ACADEMIC_UNIVERSITIES.find(
      (item) =>
        normalizeAcademicText(item.name) === normalized ||
        normalizeAcademicText(item.shortName) === normalized
    ) ?? null
  );
}

export function careersForUniversity(value?: string | null) {
  return findUniversity(value)?.careers ?? [];
}

export function hasCareerCatalog(value?: string | null) {
  return careersForUniversity(value).length > 0;
}
